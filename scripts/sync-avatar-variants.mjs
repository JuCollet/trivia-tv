// Copies the animated avatar variants from trivia-assets into the app and regenerates
// src/game/avatarVideos.ts.
//
// Source: <assets>/avatars/<name>/{neutral,happy,sad}.mp4, already processed by
// trivia-assets/scripts/process_clip.py, with <assets>/avatars/avatars.json mapping each
// folder name to the avatar id used by the app and the server (a01…a81).
// Destination: assets/videos/avatars/<id>/<emotion>.mp4 (mirrored: variants deleted from
// trivia-assets are deleted here too).
//
// Usage: npm run sync:avatars [-- <path to trivia-assets>]
// The path defaults to $TRIVIA_ASSETS, then ../trivia-assets next to this repository.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const EMOTIONS = ['neutral', 'happy', 'sad'];
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const assets = resolve(process.argv[2] ?? process.env.TRIVIA_ASSETS ?? join(root, '..', 'trivia-assets'));
const sourceDir = join(assets, 'avatars');
const targetDir = join(root, 'assets', 'videos', 'avatars');
const moduleFile = join(root, 'src', 'game', 'avatarVideos.ts');

const indexFile = join(sourceDir, 'avatars.json');
if (!existsSync(indexFile)) {
  console.error(`${indexFile} not found. Pass the trivia-assets folder: npm run sync:avatars -- <path>`);
  process.exit(1);
}
const avatars = JSON.parse(readFileSync(indexFile, 'utf8'));

const sameFile = (a, b) => existsSync(b) && statSync(a).size === statSync(b).size && readFileSync(a).equals(readFileSync(b));

const found = {};
let copied = 0;
for (const { id, folder } of avatars) {
  for (const emotion of EMOTIONS) {
    const source = join(sourceDir, folder, `${emotion}.mp4`);
    if (!existsSync(source)) continue;
    const target = join(targetDir, id, `${emotion}.mp4`);
    if (!sameFile(source, target)) {
      mkdirSync(dirname(target), { recursive: true });
      copyFileSync(source, target);
      copied += 1;
    }
    (found[id] ??= []).push(emotion);
  }
}

// Mirror: drop what is no longer in trivia-assets.
let removed = 0;
if (existsSync(targetDir)) {
  for (const entry of readdirSync(targetDir)) {
    const dir = join(targetDir, entry);
    if (!statSync(dir).isDirectory()) {
      rmSync(dir);
      removed += 1;
      continue;
    }
    for (const file of readdirSync(dir)) {
      if (!found[entry]?.includes(file.replace(/\.mp4$/, ''))) {
        rmSync(join(dir, file));
        removed += 1;
      }
    }
    if (readdirSync(dir).length === 0) rmSync(dir, { recursive: true });
  }
}

const ids = Object.keys(found).sort();
const lines = ids.map((id) => {
  const entries = found[id]
    .map((emotion) => `    ${emotion}: require('../../assets/videos/avatars/${id}/${emotion}.mp4'),`)
    .join('\n');
  return `  ${id}: {\n${entries}\n  },`;
});
writeFileSync(
  moduleFile,
  `// Generated by scripts/sync-avatar-variants.mjs (npm run sync:avatars): do not edit by hand.
// Animated variants of the avatars that have some, keyed by avatar id. Each video is square,
// composited on the seat navy (colors.seat), with the head framed like the still image.
// Static requires, so that Metro bundles each video.
import type { VideoSource } from 'expo-video';

// neutral: lobby idle. happy / sad: positive / negative awards (sad or angry).
export type AvatarEmotion = 'neutral' | 'happy' | 'sad';

const VIDEOS: Record<string, Partial<Record<AvatarEmotion, VideoSource>>> = {
${lines.join('\n')}
};

export function avatarVideo(id: string, emotion: AvatarEmotion): VideoSource | undefined {
  return VIDEOS[id]?.[emotion];
}
`,
);

const variants = ids.reduce((n, id) => n + found[id].length, 0);
console.log(
  `${variants} variant(s) for ${ids.length} avatar(s) from ${sourceDir}: ${copied} copied, ${removed} removed. ` +
    `Wrote ${moduleFile.replace(`${root}/`, '')}.`,
);
